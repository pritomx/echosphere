#!/usr/bin/env python3
"""
EchoSphere — NISAR HDF5 processing pipeline
===========================================
Team THEIA · NASA Space Apps Challenge 2026 · "Dancing with the SARs"

What this script does
---------------------
1. Scans  data/raw/  for NISAR HDF5 files (*.h5) that YOU downloaded from NASA / ASF.
2. Opens each file, discovers the science datasets and the geolocation grids.
3. Reads real metadata (product type, acquisition time, granule id, maturity...).
4. Converts / reprojects / downsamples the data for the web.
5. Writes small PNG overlays (< 1 MB each) into  data/processed/.
6. For two or more compatible GCOV observations of the same place it computes
   real backscatter change statistics and an *approximate* open-water mask.
7. Writes  data/manifest.js , which the website loads with a normal <script> tag.

Nothing here is invented: every number written to the manifest is computed from
the files in data/raw/. If data/raw/ is empty, an empty manifest is written and
the website automatically falls back to clearly-labelled DEMO data.

Heavy libraries (h5py, numpy, rasterio, pyproj, Pillow) are imported only when
there is at least one file to process, so an empty run works on any Python 3.10+.

Usage:
    python process_nisar.py
"""

