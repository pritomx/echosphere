def main():
    log("EchoSphere NISAR processor")
    log(f"  raw data : {RAW_DIR}")
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    files = sorted(p for p in RAW_DIR.iterdir() if p.suffix.lower() in (".h5", ".hdf5", ".he5"))
    info = {"generatedAt": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
            "filesFound": [p.name for p in files], "processed": [], "failed": []}

    if not files:
        write_manifest([], info)
        log("  No .h5 files in data/raw/ — nothing to process.")
        log("PASS")
        log("Empty manifest generated.")
        return 0

    try:
        import h5py, numpy, rasterio, pyproj, PIL  # noqa: F401  (check once, clearly)
    except ImportError as exc:
        log(f"ERROR: missing dependency ({exc}). Run:  pip install -r requirements.txt")
        return 1

    # Remove overlays from a previous run so the folder matches the new manifest.
    for old in OUT_DIR.glob("*.png"):
        old.unlink()

    loaded = []
    for p in files:
        log(f"\n→ {p.name}")
        try:
            it = load_file(p)
            log(f"  product {it['product']} ({it['band']}), acquired {it['acq']['datetime']}, dataset /{it['layer']['path']}")
            loaded.append(it)
        except UnsupportedFile as exc:
            fail(info, p.name, exc)
        except (OSError, ValueError, KeyError) as exc:   # corrupt / non-HDF5 / unexpected layout
            fail(info, p.name, UnsupportedFile(f"{type(exc).__name__}: {exc}", [], ["readable NISAR L2 HDF5"]))

    records = []
    for n, site in enumerate(assign_sites(loaded) if loaded else [], start=1):
        site_id = f"nisar-site-{n}"
        gcov = [it for it in site["items"] if it["product"] == "GCOV"]
        # Only same frequency + polarisation observations are compared with each other.
        by_key = {}
        for it in gcov:
            by_key.setdefault((it["layer"]["frequency"], it["layer"]["term"]), []).append(it)
        for key, group in by_key.items():
            try:
                records += process_gcov_group(group, f"{site_id}-{key[1].lower()}" if len(by_key) > 1 else site_id)
                info["processed"] += [g["file"] for g in group]
            except (UnsupportedFile, ValueError, MemoryError) as exc:
                for g in group:
                    fail(info, g["file"], exc if isinstance(exc, UnsupportedFile) else UnsupportedFile(str(exc)))
        others = [it for it in site["items"] if it["product"] != "GCOV"]
        for i, it in enumerate(sorted(others, key=lambda x: parse_date(x["acq"]["datetime"]))):
            try:
                records.append(process_single(it, site_id, i))
                info["processed"].append(it["file"])
            except (UnsupportedFile, ValueError, MemoryError) as exc:
                fail(info, it["file"], exc if isinstance(exc, UnsupportedFile) else UnsupportedFile(str(exc)))

    for png in OUT_DIR.glob("*.png"):
        assert png.stat().st_size < MAX_PNG_BYTES, f"{png.name} exceeds 1 MB"
    write_manifest(records, info)
    log(f"\nSummary: {len(info['processed'])} file(s) processed, {len(info['failed'])} failed, {len(records)} record(s).")
    log(f"Manifest written to {MANIFEST_PATH.relative_to(ROOT)}")
    log("PASS" if records else "PARTIAL — no usable records; the website will show DEMO data.")
    return 0


def fail(info, name, exc):
    log(f"  ✗ SKIPPED {name}: {exc}")
    if getattr(exc, "found", None):
        log("    found:    " + "\n              ".join(map(str, exc.found)))
    if getattr(exc, "expected", None):
        log("    expected: " + "\n              ".join(map(str, exc.expected)))
    info["failed"].append({"file": name, "reason": str(exc)})


