# 4. Per-product readers
# ==========================================================================
def read_gcov(h5, band, meta):
    """GCOV = geocoded covariance. The diagonal terms (e.g. HHHH) are LINEAR backscatter power."""
    root = f"science/{band}/GCOV/grids"
    candidates = []
    for freq in ("frequencyA", "frequencyB"):
        for term in GCOV_TERMS:
            p = f"{root}/{freq}/{term}"
            if p in h5:
                candidates.append((p, freq, term))
    if not candidates:
        raise UnsupportedFile("no GCOV backscatter term found",
                              found=[p for p, *_ in list_datasets(h5) if "/GCOV/" in p][:15],
                              expected=[f"{root}/frequencyA/{t}" for t in GCOV_TERMS])
    path, freq, term = candidates[0]
    layer = read_grid_layer(h5, path)
    import numpy as np
    layer["data"][layer["data"] <= 0] = np.nan   # log10 of <= 0 is undefined → no data
    # NISAR GCOV ships a per-pixel validity "mask" next to the covariance terms:
    # 0 = invalid / outside the swath, 255 = fill; other values mark valid samples.
    mpath = f"{root}/{freq}/mask"
    if mpath in h5 and h5[mpath].shape == h5[path].shape:
        step = layer["readStep"]
        m = h5[mpath][::step, ::step]
        bad = (m == 0) | (m == 255)
        layer["data"][bad] = np.nan
        layer["maskApplied"] = f"/{mpath}: {int(bad.sum())} of {bad.size} pixels invalid (0 or 255)"
    else:
        layer["maskApplied"] = None
    layer.update({"frequency": freq, "term": term})
    return layer


def read_gunw(h5, band, meta):
    """GUNW = geocoded unwrapped interferogram. Unwrapped phase (radians) ∝ line-of-sight motion."""
    root = f"science/{band}/GUNW/grids"
    hits = find_named(h5, root, "unwrappedPhase")
    if not hits:
        raise UnsupportedFile("no unwrappedPhase layer in GUNW",
                              found=[p for p, *_ in list_datasets(h5) if "/GUNW/" in p][:15],
                              expected=[f"{root}/frequencyA/unwrappedInterferogram/<pol>/unwrappedPhase"])
    layer = read_grid_layer(h5, hits[0])
    # Wavelength lets us convert phase to line-of-sight displacement: d = -λ·φ / (4π)
    wavelength = None
    for name in ("centerFrequency", "centerFrequencyA"):
        f = walk_up(h5, hits[0], name) or next(iter(find_named(h5, f"science/{band}", name)), None)
        if f:
            hz = float(decode(h5[f][()]))
            if hz > 0:
                wavelength = 299_792_458.0 / hz
                layer["wavelengthSource"] = f
                break
    layer["wavelength"] = wavelength
    return layer


def read_goff(h5, band, meta):
    """GOFF = geocoded pixel offsets: how far features moved between two acquisitions."""
    root = f"science/{band}/GOFF/grids"
    along = find_named(h5, root, "alongTrackOffset")
    rng = find_named(h5, root, "slantRangeOffset")
    pairs = [(a, a.rsplit("/", 1)[0] + "/slantRangeOffset") for a in along
             if a.rsplit("/", 1)[0] + "/slantRangeOffset" in rng]
    if not pairs:
        raise UnsupportedFile("no alongTrackOffset/slantRangeOffset pair in GOFF",
                              found=[p for p, *_ in list_datasets(h5) if "/GOFF/" in p][:15],
                              expected=[f"{root}/frequencyA/pixelOffsets/<pol>/layer1/alongTrackOffset (+ slantRangeOffset)"])
    a_path, r_path = pairs[0]
    a = read_grid_layer(h5, a_path)
    r = read_grid_layer(h5, r_path)
    import numpy as np
    a["along"] = a["data"]
    a["range"] = r["data"]
    a["data"] = np.hypot(a["data"], r["data"])   # magnitude of the offset vector (radar geometry)
    a["rangePath"] = r_path
    return a


READERS = {"GCOV": read_gcov, "GUNW": read_gunw, "GOFF": read_goff}


def acquisition_info(meta, product):
    """Pick real acquisition times from identification metadata."""
    def first(*keys):
        for k in keys:
            if meta.get(k):
                return str(meta[k]), k
        return None, None

    if product == "GCOV":
        start, key = first("zeroDopplerStartTime", "referenceZeroDopplerStartTime")
        return {"datetime": start, "dateSource": key}
    ref, rkey = first("referenceZeroDopplerStartTime")
    sec, skey = first("secondaryZeroDopplerStartTime")
    return {"datetime": sec or ref, "dateSource": skey or rkey, "referenceDatetime": ref, "secondaryDatetime": sec}


def parse_date(text):
    if not text:
        return None
    try:
        return _dt.datetime.fromisoformat(text.replace("Z", "").split(".")[0])
    except ValueError:
        return None


def find_maturity(meta):
    """NISAR maturity/processing descriptors differ between releases. Report what the file says."""
    for key in meta:
        if "maturity" in key.lower():
            return str(meta[key]), key
    for key in ("processingType", "productVersion", "productSpecificationVersion"):
        if meta.get(key):
            return f"{key}: {meta[key]}", key
    return None, None


# ==========================================================================
# 5. Processing one file
# ==========================================================================
def load_file(path):
    import h5py
    with h5py.File(path, "r") as h5:
        band, product, declared = detect_product(h5)
        if product not in READERS:
            datasets = list_datasets(h5)
            raise UnsupportedFile(
                f"unsupported or unrecognised product ({product or 'none detected'})",
                found=[f"{p} {s} {d}" for p, s, d in datasets[:20]] + (["..."] if len(datasets) > 20 else []),
                expected=["/science/LSAR/GCOV", "/science/LSAR/GUNW", "/science/LSAR/GOFF"],
            )
        meta = read_identification(h5, band)
        layer = READERS[product](h5, band, meta)

    acq = acquisition_info(meta, product)
    if not acq["datetime"] or not parse_date(acq["datetime"]):
        raise UnsupportedFile("no readable acquisition time in identification metadata",
                              found=sorted(meta.keys()), expected=["zeroDopplerStartTime or referenceZeroDopplerStartTime"])
    maturity, maturity_key = find_maturity(meta)
    granule = meta.get("granuleId")
    return {
        "file": path.name, "band": band, "product": product, "declaredProductType": declared,
        "meta": meta, "layer": layer, "acq": acq,
        "granule": str(granule) if granule else path.stem,
        "granuleSource": "identification/granuleId" if granule else "file name (granuleId not present in file)",
        "maturity": maturity, "maturitySource": maturity_key and f"identification/{maturity_key}",
    }


def gcov_stats(db, grid, bounds, threshold=DEFAULT_WATER_THRESHOLD_DB):
    import numpy as np
    ok = np.isfinite(db)
    n = int(ok.sum())
    if n == 0:
        return None
    px = pixel_area_km2(grid, bounds)
    water = ok & (db < threshold)
    return {
        "meanBackscatterDb": round_or_none(np.nanmean(db), 2),
        "openWaterPercent": round_or_none(100 * water.sum() / n, 2),
        "openWaterKm2": round_or_none(water.sum() * px, 1),
        "validPixels": n,
        "analyzedAreaKm2": round_or_none(n * px, 1),
        "waterCurve": {"thresholdsDb": WATER_CURVE,
                       "percent": [round_or_none(100 * (ok & (db < t)).sum() / n, 2) for t in WATER_CURVE]},
    }


def process_gcov_group(items, site_id):
    """Put every GCOV observation of one site on a shared grid, then compute change between neighbours."""
    import numpy as np
    items.sort(key=lambda it: parse_date(it["acq"]["datetime"]))
    grid = web_grid_for([it["layer"] for it in items], OVERLAY_MAX_DIM)
    small = web_grid_for([it["layer"] for it in items], GRID_MAX_DIM)
    bounds = latlon_bounds(grid)
    records, prev = [], None
    for idx, it in enumerate(items):
        L = it["layer"]
        # --- dB conversion: σ(dB) = 10·log10(σ_linear). Averaging happens in LINEAR
        #     power during reprojection, and only then do we convert to dB.
        with np.errstate(invalid="ignore", divide="ignore"):
            db = 10 * np.log10(reproject_to(L, grid))
            db_small = 10 * np.log10(reproject_to(L, small))
        rid = f"{site_id}-gcov-{idx + 1}"
        size, dims = save_png(ramp(db, -25, 0, GRAY), OUT_DIR / f"{rid}_backscatter.png")
        water_rgba = np.zeros(db.shape + (4,), dtype="uint8")
        water_rgba[np.isfinite(db) & (db < DEFAULT_WATER_THRESHOLD_DB)] = (0, 200, 255, 220)
        wsize, _ = save_png(water_rgba, OUT_DIR / f"{rid}_water.png")
        stats = gcov_stats(db, grid, bounds)
        if stats is None:
            log(f"  ! {it['file']}: no valid backscatter pixels after reprojection — skipped")
            continue
        rec = base_record(it, rid, site_id, bounds)
        rec.update({
            "overlay": f"data/processed/{rid}_backscatter.png",
            "waterOverlay": f"data/processed/{rid}_water.png",
            "changeOverlay": None,
            "polarization": L["term"], "frequency": L["frequency"],
            "units": "dB (10·log10 of linear backscatter)",
            "grid": encode_grid(db_small, *DB_GRID_RANGE),
            "stats": {**stats, "thresholdDb": DEFAULT_WATER_THRESHOLD_DB, "percentChanged": None, "meanChangeDb": None},
        })
        rec["processing"].update({"outputPixels": list(dims), "outputBytes": size + wsize,
                                  "conversion": "linear power → dB (10·log10); values ≤ 0 treated as no data"})
        if prev is not None:
            # --- Change detection: Δσ = σ_after(dB) − σ_before(dB), pixel by pixel on the shared grid.
            diff = db - prev["db"]
            ok = np.isfinite(diff)
            if ok.sum() > 0:
                d = diff[ok]
                csize, _ = save_png(ramp(diff, -6, 6, DIVERGING), OUT_DIR / f"{rid}_change.png")
                counts, _ = np.histogram(np.clip(d, HIST_EDGES[0], HIST_EDGES[-1]), bins=HIST_EDGES)
                px = pixel_area_km2(grid, bounds)
                both = np.isfinite(db) & np.isfinite(prev["db"])
                w_before = both & (prev["db"] < DEFAULT_WATER_THRESHOLD_DB)
                w_after = both & (db < DEFAULT_WATER_THRESHOLD_DB)
                d0, d1 = parse_date(prev["rec"]["datetime"]), parse_date(rec["datetime"])
                rec["changeOverlay"] = f"data/processed/{rid}_change.png"
                rec["previousId"] = prev["rec"]["id"]
                rec["stats"].update({
                    "meanChangeDb": round_or_none(d.mean(), 3),
                    "percentChanged": round_or_none(100 * (np.abs(d) >= CHANGE_THRESHOLD_DB).sum() / d.size, 2),
                    "changedAreaKm2": round_or_none((np.abs(d) >= CHANGE_THRESHOLD_DB).sum() * px, 1),
                    "changeThresholdDb": CHANGE_THRESHOLD_DB,
                    "overlapPixels": int(d.size),
                    "waterBeforePercent": round_or_none(100 * w_before.sum() / both.sum(), 2),
                    "waterAfterPercent": round_or_none(100 * w_after.sum() / both.sum(), 2),
                    "waterAreaChangeKm2": round_or_none((w_after.sum() - w_before.sum()) * px, 1),
                    "intervalDays": round_or_none((d1 - d0).total_seconds() / 86400, 1),
                    "histogram": {"edgesDb": HIST_EDGES, "counts": [int(c) for c in counts],
                                  "note": "values beyond ±15 dB are counted in the outermost bins"},
                })
                rec["processing"]["outputBytes"] += csize
        prev = {"db": db, "rec": rec}
        records.append(rec)
    return records


def process_single(it, site_id, idx):
    """GUNW / GOFF: one file already represents a change between two dates."""
    import numpy as np
    L = it["layer"]
    grid = web_grid_for([L], OVERLAY_MAX_DIM)
    small = web_grid_for([L], GRID_MAX_DIM)
    bounds = latlon_bounds(grid)
    rid = f"{site_id}-{it['product'].lower()}-{idx + 1}"
    rec = base_record(it, rid, site_id, bounds)
    vals = reproject_to(L, grid)
    ok = np.isfinite(vals)
    if not ok.any():
        raise UnsupportedFile("layer contains no valid pixels after reprojection", [L["path"]], ["finite values"])
    v = vals[ok]
    units = L.get("units") or "units not stated in file"
    if it["product"] == "GUNW":
        lim = float(np.nanpercentile(np.abs(v), 98)) or 1.0
        size, dims = save_png(ramp(vals, -lim, lim, DIVERGING), OUT_DIR / f"{rid}_deformation.png")
        stats = {"minPhase": round_or_none(v.min(), 3), "maxPhase": round_or_none(v.max(), 3),
                 "meanPhase": round_or_none(v.mean(), 3), "phaseUnits": units, "legendRange": [-lim, lim]}
        if L.get("wavelength"):
            los = -L["wavelength"] * v / (4 * math.pi)
            stats.update({"minDisplacement": round_or_none(los.min(), 4), "maxDisplacement": round_or_none(los.max(), 4),
                          "meanDisplacement": round_or_none(los.mean(), 4), "displacementUnits": "m (line of sight, relative)",
                          "wavelengthM": round_or_none(L["wavelength"], 5),
                          "displacementMethod": "d = −λ·φ/(4π); relative to an arbitrary reference; sign convention not verified by EchoSphere"})
        rec.update({"motionKind": "Unwrapped interferometric phase (line-of-sight change between two dates)"})
        grid_vals = reproject_to(L, small)
        rec["grid"] = encode_grid(grid_vals, -lim, lim)
    else:
        lim = float(np.nanpercentile(v, 98)) or 1.0
        size, dims = save_png(ramp(vals, 0, lim, MAGNITUDE), OUT_DIR / f"{rid}_motion.png")
        along = reproject_to(L, grid, L["along"])
        rng = reproject_to(L, grid, L["range"])
        stats = {"minDisplacement": round_or_none(v.min(), 3), "maxDisplacement": round_or_none(v.max(), 3),
                 "meanDisplacement": round_or_none(v.mean(), 3), "displacementUnits": units,
                 "meanAlongTrack": round_or_none(np.nanmean(along), 3), "meanSlantRange": round_or_none(np.nanmean(rng), 3),
                 "direction": "Radar geometry only (along-track / slant-range); geographic direction not derived",
                 "legendRange": [0, lim]}
        rec.update({"motionKind": "Pixel-offset magnitude (displacement between two dates — NOT velocity)"})
        rec["grid"] = encode_grid(reproject_to(L, small), 0, lim)
    d0, d1 = parse_date(it["acq"].get("referenceDatetime")), parse_date(it["acq"].get("secondaryDatetime"))
    if d0 and d1:
        stats["intervalDays"] = round_or_none((d1 - d0).total_seconds() / 86400, 1)
    stats["validPixels"] = int(ok.sum())
    stats["analyzedAreaKm2"] = round_or_none(ok.sum() * pixel_area_km2(grid, bounds), 1)
    rec.update({"overlay": None, "changeOverlay": None, "motionOverlay": f"data/processed/{rec['id']}_{'deformation' if it['product'] == 'GUNW' else 'motion'}.png",
                "units": units, "stats": stats})
    rec["processing"].update({"outputPixels": list(dims), "outputBytes": size})
    return rec


def base_record(it, rid, site_id, bounds):
    L = it["layer"]
    dtm = it["acq"]["datetime"]
    return {
        "id": rid, "site": site_id, "provenance": "REAL NISAR",
        "name": f"NISAR {it['product']} · {(bounds[0][0] + bounds[1][0]) / 2:.3f}°, {(bounds[0][1] + bounds[1][1]) / 2:.3f}°",
        "bounds": bounds, "date": dtm[:10], "datetime": dtm, "dateSource": f"identification/{it['acq']['dateSource']}",
        "referenceDatetime": it["acq"].get("referenceDatetime"), "secondaryDatetime": it["acq"].get("secondaryDatetime"),
        "product": it["product"], "declaredProductType": it["declaredProductType"], "band": it["band"],
        "maturity": it["maturity"], "maturitySource": it["maturitySource"],
        "granule": it["granule"], "granuleSource": it["granuleSource"],
        "sourceFile": it["file"],
        "processing": {
            "dataset": "/" + L["path"], "nativeShape": L["nativeShape"], "nativeSpacing": L["nativeSpacing"],
            "sourceEpsg": L["epsg"], "outputProjection": "EPSG:3857 (Web Mercator, for Leaflet)",
            "readStride": L["readStep"], "resampling": "average",
            "noData": (f"_FillValue={L['fill']}" if L["fill"] is not None else "non-finite values") + (f"; validity mask {L['maskApplied']}" if L.get("maskApplied") else ""),
            "processedAt": _dt.datetime.now(_dt.timezone.utc).isoformat(timespec="seconds"),
        },
    }


def assign_sites(items):
    """Group observations that cover roughly the same place (bounding-box overlap)."""
    from rasterio.transform import array_bounds
    from rasterio.warp import transform_bounds
    for it in items:
        h, w = it["layer"]["data"].shape
        l, b, r, t = array_bounds(h, w, it["layer"]["transform"])
        it["ll"] = transform_bounds(f"EPSG:{it['layer']['epsg']}", "EPSG:4326", l, b, r, t)
    sites = []
    for it in items:
        for s in sites:
            a, c = it["ll"], s["ll"]
            ix = max(0, min(a[2], c[2]) - max(a[0], c[0])) * max(0, min(a[3], c[3]) - max(a[1], c[1]))
            smaller = min((a[2] - a[0]) * (a[3] - a[1]), (c[2] - c[0]) * (c[3] - c[1]))
            if smaller > 0 and ix / smaller > 0.3:
                s["items"].append(it)
                break
        else:
            sites.append({"ll": it["ll"], "items": [it]})
    return sites


