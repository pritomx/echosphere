def log(msg=""):
    print(msg, flush=True)


def decode(value):
    """HDF5 strings often arrive as bytes or 1-element numpy arrays. Make them plain Python."""
    try:
        import numpy as np
        if isinstance(value, np.ndarray):
            if value.size == 1:
                value = value.reshape(-1)[0]
            else:
                return [decode(v) for v in value.tolist()]
        if isinstance(value, np.generic):
            value = value.item()
    except ImportError:
        pass
    if isinstance(value, bytes):
        return value.decode("utf-8", errors="replace").strip()
    if isinstance(value, str):
        return value.strip()
    return value


def round_or_none(x, nd=3):
    if x is None:
        return None
    x = float(x)
    if math.isnan(x) or math.isinf(x):
        return None
    return round(x, nd)


def write_manifest(records, info):
    """Write data/manifest.js as plain JavaScript (works when index.html is opened via file://)."""
    MANIFEST_PATH.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(records, indent=2, ensure_ascii=False)
    text = (
        "// AUTO-GENERATED by process_nisar.py — do not edit by hand.\n"
        "// Contains ONLY records computed from real NISAR HDF5 files found in data/raw/.\n"
        "// An empty array means no real files were processed; the site then shows DEMO data.\n"
        f"const NISAR_MANIFEST = {body};\n\n"
        f"const NISAR_MANIFEST_INFO = {json.dumps(info, indent=2, ensure_ascii=False)};\n"
    )
    MANIFEST_PATH.write_text(text, encoding="utf-8")


# ==========================================================================
# 1. Opening HDF5 and discovering datasets
# ==========================================================================
# An HDF5 file is like a folder tree: "groups" are folders and "datasets" are
# arrays. NISAR products put the science layers under /science/<band>/<PRODUCT>/
# and the descriptive metadata under /science/<band>/identification/.

def list_datasets(h5):
    """Return [(path, shape, dtype)] for every dataset in the file."""
    import h5py
    found = []

    def visit(name, obj):
        if isinstance(obj, h5py.Dataset):
            found.append((name, obj.shape, str(obj.dtype)))

    h5.visititems(visit)
    return found


def detect_product(h5):
    """Find which band (LSAR/SSAR) and product (GCOV/GUNW/GOFF) the file contains."""
    for band in BANDS:
        ident = f"science/{band}/identification"
        declared = None
        if ident in h5 and "productType" in h5[ident]:
            declared = decode(h5[ident]["productType"][()])
        for product in ("GCOV", "GUNW", "GOFF"):
            if f"science/{band}/{product}" in h5:
                return band, product, declared
        if declared:
            return band, str(declared).upper(), declared
    return None, None, None


def read_identification(h5, band):
    """Read every scalar in the identification group as real metadata."""
    meta = {}
    ident = f"science/{band}/identification"
    if ident not in h5:
        return meta
    for key, obj in h5[ident].items():
        try:
            if obj.shape in ((), (1,)):
                meta[key] = decode(obj[()])
        except (TypeError, AttributeError, OSError):
            continue  # compound / unusual objects are simply not needed here
    return meta


def find_named(h5, root, name):
    """Return every dataset path under `root` whose last component equals `name`."""
    import h5py
    hits = []
    if root not in h5:
        return hits

    def visit(sub, obj):
        if isinstance(obj, h5py.Dataset) and sub.split("/")[-1] == name:
            hits.append(f"{root}/{sub}")

    h5[root].visititems(visit)
    return sorted(hits)


def walk_up(h5, ds_path, name):
    """Look for a sibling dataset `name` in the dataset's group, then in each parent group."""
    parts = ds_path.split("/")[:-1]
    while parts:
        candidate = "/".join(parts + [name])
        if candidate in h5:
            return candidate
        parts.pop()
    return None


# ==========================================================================
# 2. Geolocation
# ==========================================================================
# NISAR L2 products (GCOV, GUNW, GOFF) are already on a map grid. Each layer has
# 1-D "xCoordinates" and "yCoordinates" (pixel centres, in metres for UTM or
# degrees for EPSG:4326) and a "projection" dataset whose attributes hold the
# EPSG code. From those we build an affine transform: pixel (row, col) -> map x/y.

def read_epsg(h5, ds_path):
    proj_path = walk_up(h5, ds_path, "projection")
    if not proj_path:
        return None, None
    ds = h5[proj_path]
    for attr in ("epsg_code", "epsg", "EPSG"):
        if attr in ds.attrs:
            return int(decode(ds.attrs[attr])), f"{proj_path}@{attr}"
    try:
        value = decode(ds[()])
        if isinstance(value, (int, float)) and 1000 < int(value) < 100000:
            return int(value), proj_path
    except (TypeError, ValueError, OSError):
        pass
    return None, proj_path


def read_grid_layer(h5, ds_path):
    """Read a 2-D layer (strided if large) + its georeferencing. Returns a dict."""
    import numpy as np
    from rasterio.transform import Affine

    ds = h5[ds_path]
    if ds.ndim != 2:
        raise UnsupportedFile(f"{ds_path} is not 2-D", [f"{ds_path} shape={ds.shape}"], ["2-D raster layer"])

    xpath = walk_up(h5, ds_path, "xCoordinates")
    ypath = walk_up(h5, ds_path, "yCoordinates")
    epsg, epsg_src = read_epsg(h5, ds_path)
    missing = [n for n, v in (("xCoordinates", xpath), ("yCoordinates", ypath), ("projection EPSG code", epsg)) if not v]
    if missing:
        raise UnsupportedFile(
            f"geolocation incomplete for {ds_path}",
            found=[f"xCoordinates: {xpath}", f"yCoordinates: {ypath}", f"projection: {epsg_src}"],
            expected=[f"{m} next to {ds_path} or in a parent group" for m in missing],
        )

    # --- Downsampling on read -------------------------------------------------
    # A full NISAR frame can be tens of thousands of pixels wide. Reading every
    # `step`-th pixel keeps memory reasonable; the later reprojection uses
    # *average* resampling to smooth the result onto the web grid.
    rows, cols = ds.shape
    step = max(1, math.ceil(max(rows, cols) / READ_MAX_DIM))
    data = ds[::step, ::step].astype("float32")
    x = h5[xpath][::step].astype("float64")
    y = h5[ypath][::step].astype("float64")
    if len(x) < 2 or len(y) < 2 or len(x) != data.shape[1] or len(y) != data.shape[0]:
        raise UnsupportedFile(
            "coordinate arrays do not match the raster",
            found=[f"data {data.shape}", f"x {len(x)}", f"y {len(y)}"],
            expected=["len(x) == columns and len(y) == rows"],
        )

    # --- No-data handling ------------------------------------------------------
    fill = ds.attrs.get("_FillValue")
    if fill is not None:
        fill = decode(fill)
        if isinstance(fill, (int, float)) and not math.isnan(float(fill)):
            data[data == fill] = np.nan
    data[~np.isfinite(data)] = np.nan

    dx = x[1] - x[0]
    dy = y[1] - y[0]
    # Coordinates are pixel centres; the transform needs the outer corner.
    transform = Affine(dx, 0, x[0] - dx / 2, 0, dy, y[0] - dy / 2)
    units = decode(ds.attrs.get("units")) if "units" in ds.attrs else None
    return {
        "data": data, "transform": transform, "epsg": epsg, "path": ds_path,
        "nativeShape": [int(rows), int(cols)], "readStep": step,
        "nativeSpacing": [round(abs(float(h5[xpath][1] - h5[xpath][0])), 4),
                          round(abs(float(h5[ypath][1] - h5[ypath][0])), 4)],
        "units": units, "fill": fill,
    }


def web_grid_for(layers, max_dim):
    """Common Web-Mercator (EPSG:3857) grid covering all `layers`.

    Leaflet displays maps in Web Mercator and stretches an image overlay linearly
    between its corners, so rendering overlays on an EPSG:3857 grid makes them line
    up correctly with the basemap."""
    from rasterio.transform import Affine, array_bounds
    from rasterio.warp import transform_bounds

    boxes = []
    for L in layers:
        h, w = L["data"].shape
        left, bottom, right, top = array_bounds(h, w, L["transform"])
        boxes.append(transform_bounds(f"EPSG:{L['epsg']}", "EPSG:3857", left, bottom, right, top, densify_pts=21))
    left = min(b[0] for b in boxes); bottom = min(b[1] for b in boxes)
    right = max(b[2] for b in boxes); top = max(b[3] for b in boxes)
    res = max(right - left, top - bottom) / max_dim
    width = max(2, int(math.ceil((right - left) / res)))
    height = max(2, int(math.ceil((top - bottom) / res)))
    return {"transform": Affine(res, 0, left, 0, -res, top), "width": width, "height": height,
            "bounds3857": (left, bottom, right, top), "res": res}


def reproject_to(layer, grid, values=None):
    """Reproject a layer (or replacement `values` on the same geometry) onto a web grid."""
    import numpy as np
    from rasterio.crs import CRS
    from rasterio.warp import Resampling, reproject

    src = layer["data"] if values is None else values
    dst = np.full((grid["height"], grid["width"]), np.nan, dtype="float32")
    reproject(
        source=src, destination=dst,
        src_transform=layer["transform"], src_crs=CRS.from_epsg(layer["epsg"]),
        dst_transform=grid["transform"], dst_crs=CRS.from_epsg(3857),
        src_nodata=np.nan, dst_nodata=np.nan, resampling=Resampling.average,
    )
    return dst


def latlon_bounds(grid):
    """Leaflet bounds [[south, west], [north, east]] of a 3857 grid."""
    from pyproj import Transformer
    t = Transformer.from_crs("EPSG:3857", "EPSG:4326", always_xy=True)
    left, bottom, right, top = grid["bounds3857"]
    west, south = t.transform(left, bottom)
    east, north = t.transform(right, top)
    return [[round(south, 6), round(west, 6)], [round(north, 6), round(east, 6)]]


def pixel_area_km2(grid, bounds):
    """Approximate ground area of one web-grid pixel (Mercator scale corrected at mid-latitude)."""
    lat = (bounds[0][0] + bounds[1][0]) / 2
    side_m = grid["res"] * math.cos(math.radians(lat))
    return side_m * side_m / 1e6


# ==========================================================================
# 3. Colour maps and PNG writing (with the < 1 MB guarantee)
# ==========================================================================
def ramp(values, vmin, vmax, stops):
    """Map values to RGBA using linear colour stops [(pos 0..1, (r,g,b)), ...]. NaN -> transparent."""
    import numpy as np
    t = np.nan_to_num(np.clip((values - vmin) / (vmax - vmin), 0, 1))   # NaN pixels become transparent below
    rgba = np.zeros(values.shape + (4,), dtype="uint8")
    pos = np.array([s[0] for s in stops])
    for c in range(3):
        rgba[..., c] = np.interp(t, pos, [s[1][c] for s in stops]).astype("uint8")
    rgba[..., 3] = np.where(np.isfinite(values), 235, 0)
    return rgba


GRAY = [(0, (8, 12, 20)), (1, (235, 240, 250))]
DIVERGING = [(0, (33, 102, 172)), (0.5, (245, 245, 245)), (1, (178, 24, 43))]   # blue = decrease, red = increase
MAGNITUDE = [(0, (13, 8, 135)), (0.5, (204, 71, 120)), (1, (240, 249, 33))]


def save_png(rgba, path):
    """Save an RGBA overlay and guarantee it is below MAX_PNG_BYTES.

    Strategy: optimised PNG → palette-quantised PNG (lower 'quality') → shrink
    dimensions by 25% and retry. Fails loudly if still too large."""
    from PIL import Image
    img = Image.fromarray(rgba, "RGBA")
    for attempt in range(8):
        img.save(path, optimize=True)
        if path.stat().st_size < MAX_PNG_BYTES:
            return path.stat().st_size, img.size
        img.quantize(colors=128, method=Image.Quantize.FASTOCTREE).save(path, optimize=True)
        if path.stat().st_size < MAX_PNG_BYTES:
            return path.stat().st_size, img.size
        w, h = img.size
        img = img.resize((max(1, int(w * 0.75)), max(1, int(h * 0.75))), Image.Resampling.NEAREST)
    path.unlink(missing_ok=True)
    raise UnsupportedFile(f"could not bring {path.name} below {MAX_PNG_BYTES} bytes", [], ["PNG < 1 MB"])


def encode_grid(values, vmin, vmax):
    """Quantise a small float grid to uint8 (255 = no data) and base64 it for the manifest.

    The browser cannot read pixels from local PNGs (file:// security), so the
    exploratory threshold slider works on this small embedded grid instead."""
    import numpy as np
    q = np.full(values.shape, 255, dtype="uint8")
    ok = np.isfinite(values)
    q[ok] = np.clip(np.round((values[ok] - vmin) / (vmax - vmin) * 254), 0, 254).astype("uint8")
    return {"w": int(values.shape[1]), "h": int(values.shape[0]), "min": vmin, "max": vmax,
            "nodata": 255, "b64": base64.b64encode(q.tobytes()).decode("ascii")}


